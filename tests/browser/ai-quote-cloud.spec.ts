import {test,expect} from "@playwright/test";
import {randomUUID} from "node:crypto";
import {jsPDF} from "jspdf";
import {createGoogleSession} from "../emulator/http-helpers.mjs";

const base=process.env.EMULATOR_TEST_URL || "http://127.0.0.1:3002";
if(!["127.0.0.1","localhost"].includes(new URL(base).hostname))throw new Error("AI QA must use loopback emulators.");
test.use({baseURL:base});
test("authenticated AI compilation preserves source evidence through edit, markup, save, reopen, and PDF",async({context,page})=>{
  test.skip(process.env.QUOTEFORGE_RUN_AI_BROWSER_TESTS!=="true","Requires isolated emulator server with fake-openai-preload.mjs.");
  test.setTimeout(90000);
  const session=await createGoogleSession("owner@example.com"),id=`ai-browser-${randomUUID()}`;
  const company={id,name:"AI Quote QA",industry:"Services",email:"office@example.com",phone:"",address:"",website:"",status:"Draft",branding:{primary:"#122239",secondary:"#F5F7FA",accent:"#EE7D3B",font:"Arial",logo:""},fields:[],createdAt:new Date().toISOString(),origin:"owner"};
  const created=await session.request("/api/companies",{method:"POST",headers:{"Content-Type":"application/json"},body:JSON.stringify(company)});
  expect(created.status,await created.text()).toBe(200);
  await context.addCookies(session.cookie.split("; ").map((pair:string)=>{const i=pair.indexOf("=");return {name:pair.slice(0,i),value:pair.slice(i+1),url:base,httpOnly:true,sameSite:"Lax" as const};}));
  await context.addInitScript(()=>localStorage.setItem("quoteforge.owner.tutorial.v1",JSON.stringify({version:1,status:"skipped",step:0})));
  const errors:string[]=[];page.on("pageerror",error=>errors.push(error.message));
  await page.goto(`/companies/${id}/open`);
  await page.getByRole("textbox",{name:"Customer / Project Name",exact:false}).fill("Synthetic AI Customer");
  await page.getByLabel("Customer email",{exact:true}).fill("customer@example.com");
  await page.getByLabel("Project title",{exact:true}).fill("AI saved draft");
  const pdf=new jsPDF();pdf.text("Install trim 4 EA at $9.25",20,30);
  await page.getByLabel("Upload quote documents").setInputFiles({name:"synthetic-ai-source.pdf",mimeType:"application/pdf",buffer:Buffer.from(pdf.output("arraybuffer"))});
  await expect(page.locator('.source-document[data-document-status="ready"]')).toHaveCount(1,{timeout:30000});
  await page.getByRole("button",{name:"Generate AI Draft",exact:true}).click();
  const dialog=page.getByRole("dialog");await expect(dialog).toContainText("sent to OpenAI for this company");
  const generated=page.waitForResponse(response=>response.url().endsWith("/api/proposals/generate")&&response.request().method()==="POST");
  await dialog.getByRole("button",{name:"Generate AI draft",exact:true}).click();
  const response=await generated;expect(response.status(),JSON.stringify(await response.json())).toBe(200);
  await expect(dialog).toBeHidden();await expect(page.getByLabel("Line 1 unit price",{exact:true})).toHaveValue("9.25");
  await expect(page.locator(".preview-total strong")).toHaveText("$37.00");
  await page.getByText("Source evidence",{exact:true}).click();await expect(page.getByText("Install trim 4 EA at $9.25",{exact:true})).toBeVisible();
  await page.getByLabel("Line 1 unit price",{exact:true}).fill("10");
  await page.getByRole("button",{name:/Private pricing controls/}).click();
  await page.getByLabel("Markup type",{exact:true}).selectOption("percent");
  await page.getByLabel("Markup (%)",{exact:true}).fill("10");
  await expect(page.locator(".preview-total strong")).toHaveText("$44.00");
  await page.getByRole("checkbox",{name:/reviewed the scope/}).check();
  const saved=page.waitForResponse(value=>value.url().endsWith(`/api/tenants/${id}/drafts`)&&value.request().method()==="POST");
  await page.getByRole("button",{name:"Save draft",exact:true}).click();const record=await (await saved).json();expect(record.record.aiDraft.jobId).toBeTruthy();expect(record.record.lineItems[0].sourceReferences[0].sourceId).toBeTruthy();
  await page.reload();await page.getByRole("button",{name:/Saved drafts/}).click();await page.locator(".draft-list>button").filter({hasText:"AI saved draft"}).click();
  await expect(page.getByLabel("Line 1 unit price",{exact:true})).toHaveValue("10");await expect(page.getByText("Source evidence",{exact:true})).toBeVisible();
  const download=page.waitForEvent("download");await page.getByRole("button",{name:"Download PDF",exact:true}).click();expect((await download).suggestedFilename()).toMatch(/\.pdf$/);
  expect(errors).toEqual([]);
});
